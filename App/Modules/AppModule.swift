/// アプリを構成する機能単位（モジュール）の共通インターフェース。
///
/// `AppDelegate` は組み立て役に徹し、モジュールを生成して `start()` / `stop()` を呼ぶだけにする。
/// 機能の中身（イベントタップ、ヒントモード、設定画面など）は各モジュールのファイルに閉じ込め、
/// 後続のタスク（T37 / T48 / T54）が `AppDelegate` を触らずに自分のモジュールだけを実装できるようにする。
/// モジュール間で受け渡す値は、受け渡す側のモジュールがプロパティとして公開し、
/// 受け取る側はイニシャライザでそのモジュールを受け取る。
@MainActor
protocol AppModule: AnyObject {
    /// モジュールを開始する。開始できなかった場合は投げる（黙って続けない）。
    func start() throws

    /// モジュールを停止し、確保した資源（イベントタップ、ウィンドウなど）を解放する。
    /// `start()` が成功したモジュールに対してだけ呼ばれる。
    func stop()
}
